// Builds web/vendor/solana.js: one minified IIFE, no imports, no network at load time, so the
// Android WebView (Chromium 133+) can load it from file:///android_asset with a plain <script>.
//   cd tools && npm install && npm run bundle
import { build } from 'esbuild';
import { statSync, readFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const outfile = resolve(here, '../web/vendor/solana.js');

const result = await build({
  entryPoints: [resolve(here, 'bundle-entry.js')],
  outfile,
  bundle: true,
  format: 'iife',
  globalName: 'SolanaLib',
  platform: 'browser',
  mainFields: ['browser', 'module', 'main'],
  target: ['chrome133'],
  minify: true,
  legalComments: 'none',
  inject: [resolve(here, 'shims/buffer-global.js')],
  define: {
    'process.env.NODE_ENV': '"production"',
    global: 'globalThis',
  },
  banner: {
    js: '/* web/vendor/solana.js — generated by tools/bundle.mjs from @solana/web3.js, @solana/spl-stake-pool, @solana/spl-token (see tools/package.json for versions and licenses). Do not edit. */',
  },
  // A classic script's top-level `var SolanaLib` already lands on window; say it explicitly so the
  // name is also set when the file is evaluated somewhere `var` does not become a global.
  footer: { js: 'if(typeof window!=="undefined")window.SolanaLib=SolanaLib;' },
  metafile: true,
  logLevel: 'warning',
});

const bytes = statSync(outfile).size;
const gz = gzipSync(readFileSync(outfile)).length;
const inputs = Object.entries(result.metafile.outputs[Object.keys(result.metafile.outputs)[0]].inputs)
  .reduce((acc, [file, info]) => {
    const pkg = (file.match(/node_modules\/((?:@[^/]+\/)?[^/]+)/) || [, 'app'])[1];
    acc[pkg] = (acc[pkg] || 0) + info.bytesInOutput;
    return acc;
  }, {});
const top = Object.entries(inputs).sort((a, b) => b[1] - a[1]).slice(0, 12)
  .map(([k, v]) => `${k} ${(v / 1024).toFixed(1)} KB`).join(', ');
console.log(`web/vendor/solana.js: ${(bytes / 1024).toFixed(1)} KB minified, ${(gz / 1024).toFixed(1)} KB gzipped`);
console.log(`largest inputs: ${top}`);
